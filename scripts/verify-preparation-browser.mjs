  await page.waitForFunction(()=>document.getElementById('rendered-input').value.includes('local-chat-template'));
  await page.setViewportSize({width:390,height:844});await page.locator('#prepare').click();
  await page.waitForFunction(()=>document.getElementById('prepare-status').textContent.includes('门禁通过'));
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:'artifacts/preparation-browser/mobile.png',fullPage:true});
  await page.locator('#rendered-input').fill('{}');await page.locator('#rendered-input').dispatchEvent('input');
  assert.equal(await page.locator('#export-preparation').isDisabled(),true);
  assert.equal(await page.locator('#prepare-results').isHidden(),true);
  checks.push('390px layout stays within viewport; edits clear stale evidence');
  assert.deepEqual(errors,[]);
  const evidence={schema:'preparation-browser-validation-v1',browser:await browser.version(),checks,errors};
  await writeFile('artifacts/preparation-browser/summary.json',JSON.stringify(evidence,null,2)+'\n');
  console.log(JSON.stringify({checks:checks.length,errors:errors.length}));
