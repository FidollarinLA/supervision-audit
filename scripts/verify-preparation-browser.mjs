  checks.push('training JSONL exactly equals core output; tool responses remain context');
  await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:'artifacts/preparation-browser/desktop.png',fullPage:true});
  const audit=await browser.newPage();await audit.goto(address);
  await audit.locator('#file').setInputFiles({name:'prepared.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(expected.document))});
  await audit.waitForFunction(()=>document.querySelector('#metrics strong')?.textContent==='通过');
  assert.equal(await audit.locator('#metrics strong').first().textContent(),'通过');
  checks.push('prepared document imports into existing token evidence viewer');
  const handoff=await browser.newPage();await handoff.goto(address+'/prepare.html');
  await handoff.waitForFunction(()=>document.getElementById('rendered-input').value.includes('chat-multiturn'));
  await handoff.locator('#prepare').click();await handoff.waitForFunction(()=>document.getElementById('inspect-prepared').disabled===false);
  await handoff.locator('#inspect-prepared').click();await handoff.waitForURL('**/?prepared=1');
  await handoff.waitForFunction(()=>document.querySelector('#metrics strong')?.textContent==='通过');
  assert.equal(await handoff.locator('#metrics strong').first().textContent(),'通过');
  assert.equal(await handoff.evaluate(()=>sessionStorage.getItem('prepared-audit-document')),null);
  checks.push('one-click evidence handoff consumes its temporary document');
  await page.locator('#train_on_tools').uncheck();await page.locator('#train_on_reasoning').uncheck();
  assert.equal(await page.locator('#export-training').isDisabled(),true);
  await page.locator('#prepare').click();await page.waitForFunction(()=>document.getElementById('prepare-status').textContent.includes('门禁通过'));
  assert.equal(await page.locator('#prepare-metrics strong').last().textContent(),'24');
  checks.push('final-only strategy removes tool-call labels and invalidates prior export');
  await page.locator('#train_on_reasoning').check();await page.locator('#train_on_tools').check();
  await page.locator('#load-reasoning').click();await page.waitForFunction(()=>document.getElementById('rendered-input').value.includes('explicit-reasoning'));
  await page.locator('#prepare').click();await page.waitForFunction(()=>document.getElementById('prepare-status').textContent.includes('门禁通过'));
  const all=Number(await page.locator('#prepare-metrics strong').last().textContent());
  await page.locator('#train_on_reasoning').uncheck();await page.locator('#prepare').click();
  await page.waitForFunction(()=>document.getElementById('prepare-status').textContent.includes('门禁通过'));
  assert.ok(Number(await page.locator('#prepare-metrics strong').last().textContent())<all);
  checks.push('reasoning strategy works on explicitly authored template');
  await page.locator('#train_on_final_answers').uncheck();await page.locator('#train_on_tools').uncheck();
  await page.locator('#prepare').click();await page.waitForFunction(()=>document.getElementById('prepare-status').textContent.includes('no effective targets'));
  assert.equal(await page.locator('#export-training').isDisabled(),true);
  assert.equal(await page.locator('#prepare-results').isHidden(),true);
