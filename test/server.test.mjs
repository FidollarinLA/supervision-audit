import test from 'node:test';
import assert from 'node:assert/strict';
import {once} from 'node:events';
import {createStaticServer} from '../scripts/server.mjs';
test('local server serves the entry, engine and fixtures without allowing writes',async t=>{
 const server=createStaticServer();server.listen(0,'127.0.0.1');await once(server,'listening');
 t.after(()=>new Promise(resolve=>server.close(resolve)));
 const base='http://127.0.0.1:'+server.address().port;
 const page=await fetch(base+'/');assert.equal(page.status,200);
 const hub=await page.text();
 assert.match(hub,/SupervisionAudit/);
 assert.match(hub,/训练数据准备与监督验证|prepare\.html/);
 assert.match(hub,/评审验收清单/);
 assert.match(hub,/ACCEPTANCE CHECKLIST/);
 const audit=await fetch(base+'/audit.html');assert.equal(audit.status,200);assert.match(await audit.text(),/id="run"/);
 const prepare=await fetch(base+'/prepare.html');assert.equal(prepare.status,200);
 const prepareText=await prepare.text();
 assert.match(prepareText,/训练数据准备/);
 assert.match(prepareText,/id="policy-preset"/);
 assert.match(prepareText,/策略预设/);
 const presets=await fetch(base+'/traces/presets.json');assert.equal(presets.status,200);
 const catalog=await presets.json();
 assert.equal(catalog.schema,'supervision-audit/policy-presets/v1');
 assert.ok(catalog.presets.some(row=>row.id==='assistant-all'));
 assert.ok(catalog.presets.some(row=>row.id==='final-only'));
 assert.ok(catalog.presets.some(row=>row.id==='tools-and-answers'));
 const engine=await fetch(base+'/engine.js');assert.equal(engine.status,200);assert.match(engine.headers.get('content-type'),/javascript/);
 const data=await fetch(base+'/examples/healthy.json');assert.equal(data.status,200);assert.equal((await data.json()).contract,'causal-lm-unshifted-v1');
 assert.equal((await fetch(base+'/missing-file')).status,404);
 assert.equal((await fetch(base+'/',{method:'POST'})).status,405);
 assert.equal((await fetch(base+'/%2e%2e%2fREADME.md')).status,403);
});
